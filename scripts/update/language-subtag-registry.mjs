#!/usr/bin/env node

import { spawnSync } from "node:child_process";
import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";

const REGISTRY_URL =
  "https://www.iana.org/assignments/language-subtag-registry/language-subtag-registry";
const OUTPUT_PATH = resolve("packages/api/src/contracts/locale/registry/index.ts");

function parseRecord(block) {
  const fields = new Map();
  let currentKey;

  for (const line of block.split(/\r?\n/u)) {
    const match = /^([A-Za-z-]+):\s?(.*)$/u.exec(line);
    if (match) {
      currentKey = match[1];
      const values = fields.get(currentKey) ?? [];
      values.push(match[2]);
      fields.set(currentKey, values);
      continue;
    }

    if (currentKey && /^\s/u.test(line)) {
      const values = fields.get(currentKey);
      values[values.length - 1] += ` ${line.trim()}`;
    }
  }

  return {
    first(key) {
      return fields.get(key)?.[0];
    },
  };
}

function compareAscii(left, right) {
  return left < right ? -1 : left > right ? 1 : 0;
}

function sorted(values) {
  return [...values].sort(compareAscii);
}

function setExpression(values) {
  return `new Set(${JSON.stringify(sorted(values).join("|"))}.split("|"))`;
}

function mapExpression(entries) {
  return `new Map(${JSON.stringify(
    [...entries].sort(([left], [right]) => compareAscii(left, right)),
  )})`;
}

async function loadRegistry() {
  const inputArgument = process.argv[2];
  if (inputArgument) {
    return readFile(resolve(inputArgument), "utf8");
  }

  const response = await fetch(REGISTRY_URL, {
    headers: { accept: "text/plain" },
    redirect: "follow",
  });
  if (!response.ok) {
    throw new Error(`IANA registry request failed with HTTP ${response.status}.`);
  }
  return response.text();
}

const source = await loadRegistry();
const fileDate = /^File-Date:\s*(\d{4}-\d{2}-\d{2})$/mu.exec(source)?.[1];
if (!fileDate) throw new Error("The IANA registry is missing a valid File-Date header.");

const records = source.split(/^%%$/mu).slice(1).map(parseRecord);
const subtags = {
  language: new Set(),
  script: new Set(),
  region: new Set(),
  variant: new Set(),
};
const aliases = {
  language: new Map(),
  script: new Map(),
  region: new Map(),
  variant: new Map(),
};
const fullTagAliases = new Map();
const unsupportedGrandfatheredTags = new Set();
const extlangAliases = new Map();

for (const record of records) {
  const type = record.first("Type");
  const subtag = record.first("Subtag");
  const tag = record.first("Tag");
  const preferredValue = record.first("Preferred-Value");

  if (type in subtags && subtag && !subtag.includes("..")) {
    const normalizedSubtag = subtag.toLowerCase();
    const isPrivateUse =
      record.first("Scope") === "private-use" || record.first("Description") === "Private use";
    if (!isPrivateUse) subtags[type].add(normalizedSubtag);
    if (preferredValue) aliases[type].set(normalizedSubtag, preferredValue);
    continue;
  }

  if (type === "extlang" && subtag && preferredValue) {
    const prefix = record.first("Prefix");
    if (prefix)
      extlangAliases.set(`${prefix.toLowerCase()}-${subtag.toLowerCase()}`, preferredValue);
    continue;
  }

  if ((type === "grandfathered" || type === "redundant") && tag) {
    const normalizedTag = tag.toLowerCase();
    if (preferredValue) fullTagAliases.set(normalizedTag, preferredValue);
    else if (type === "grandfathered") unsupportedGrandfatheredTags.add(normalizedTag);
  }
}

for (const required of ["en", "hi", "gu", "zh"]) {
  if (!subtags.language.has(required)) throw new Error(`Registry is missing language ${required}.`);
}
for (const required of ["hant", "latn"]) {
  if (!subtags.script.has(required)) throw new Error(`Registry is missing script ${required}.`);
}
for (const required of ["gb", "tw", "us"]) {
  if (!subtags.region.has(required)) throw new Error(`Registry is missing region ${required}.`);
}

const output = `// This file is generated by scripts/update/language-subtag-registry.mjs.
// Source: ${REGISTRY_URL}
// IANA Language Subtag Registry File-Date: ${fileDate}
// Do not edit this file directly.

export const localeRegistryFileDate = ${JSON.stringify(fileDate)};

export const registeredLanguageSubtags: ReadonlySet<string> = ${setExpression(subtags.language)};
export const registeredScriptSubtags: ReadonlySet<string> = ${setExpression(subtags.script)};
export const registeredRegionSubtags: ReadonlySet<string> = ${setExpression(subtags.region)};
export const registeredVariantSubtags: ReadonlySet<string> = ${setExpression(subtags.variant)};

export const languageSubtagAliases: ReadonlyMap<string, string> = ${mapExpression(aliases.language)};
export const scriptSubtagAliases: ReadonlyMap<string, string> = ${mapExpression(aliases.script)};
export const regionSubtagAliases: ReadonlyMap<string, string> = ${mapExpression(aliases.region)};
export const variantSubtagAliases: ReadonlyMap<string, string> = ${mapExpression(aliases.variant)};
export const extlangTagAliases: ReadonlyMap<string, string> = ${mapExpression(extlangAliases)};
export const registeredTagAliases: ReadonlyMap<string, string> = ${mapExpression(fullTagAliases)};
export const unsupportedGrandfatheredTags: ReadonlySet<string> = ${setExpression(unsupportedGrandfatheredTags)};
`;

await writeFile(OUTPUT_PATH, output, "utf8");
const formatter = spawnSync(
  process.platform === "win32" ? "pnpm.cmd" : "pnpm",
  ["exec", "oxfmt", "--write", OUTPUT_PATH],
  { stdio: "inherit" },
);
if (formatter.status !== 0) throw new Error("Failed to format the generated registry module.");
console.log(`Updated ${OUTPUT_PATH} from IANA registry ${fileDate}.`);
